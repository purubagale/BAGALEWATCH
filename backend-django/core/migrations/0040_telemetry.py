# Crowdsourced telemetry intake (2026-08-30). Three plain tables plus
# v2_telemetry_samples, which is RANGE-partitioned by `received_at`
# (monthly) — Django's CreateModel can't emit `PARTITION BY`, so that one
# table is done with SeparateDatabaseAndState: Django keeps the model in
# its migration state (ORM works normally), the DB gets the partitioned
# DDL by hand. Retention (prune_telemetry.py) then aggregates and DROPs
# whole expired partitions.
#
# The `telemetry_ensure_partition(date)` plpgsql helper is created here
# and reused by the `ensure_telemetry_partitions` management command to
# roll the window forward each month.

import core.models
