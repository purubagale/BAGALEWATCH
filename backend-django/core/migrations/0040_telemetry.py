_ENSURE_PARTITION_FN = r"""
CREATE OR REPLACE FUNCTION telemetry_ensure_partition(p_month date)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    m_start date := date_trunc('month', p_month)::date;
    m_end   date := (date_trunc('month', p_month) + interval '1 month')::date;
    part    text := format('v2_telemetry_samples_%s', to_char(m_start, 'YYYYMM'));
BEGIN
    IF to_regclass(part) IS NULL THEN
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF v2_telemetry_samples FOR VALUES FROM (%L) TO (%L)',
            part, m_start, m_end
        );
    END IF;
END;
$$;
"""

_CREATE_SAMPLES = r"""
CREATE TABLE v2_telemetry_samples (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    device_id     varchar(64)  NOT NULL,
    ts            timestamptz  NOT NULL,
    received_at   timestamptz  NOT NULL,
    lat           double precision,
    lng           double precision,
    location      geography(Point, 4326),
    gps_accuracy_m real,
    cell_id       bigint,
    pci           integer,
    tac           integer,
    mcc           varchar(6)   NOT NULL DEFAULT '',
    mnc           varchar(6)   NOT NULL DEFAULT '',
    network_type  varchar(12)  NOT NULL DEFAULT 'UNKNOWN',
    rsrp_dbm      smallint,
    rsrq_db       smallint,
    rssi_dbm      smallint,
    sinr_db       smallint,
    battery_pct   smallint,
    trigger_reason varchar(10) NOT NULL DEFAULT 'periodic',
    region        varchar(100) NOT NULL DEFAULT '',
    PRIMARY KEY (id, received_at)
) PARTITION BY RANGE (received_at);

CREATE INDEX v2_telemetry_samples_device_ts_idx ON v2_telemetry_samples (device_id, ts);
CREATE INDEX v2_telemetry_samples_device_idx    ON v2_telemetry_samples (device_id);
CREATE INDEX v2_telemetry_samples_ts_idx        ON v2_telemetry_samples (ts);
CREATE INDEX v2_telemetry_samples_received_idx  ON v2_telemetry_samples (received_at);
CREATE INDEX v2_telemetry_samples_network_idx   ON v2_telemetry_samples (network_type);
CREATE INDEX v2_telemetry_samples_region_idx    ON v2_telemetry_samples (region);
CREATE INDEX v2_telemetry_samples_gix           ON v2_telemetry_samples USING GIST (location);

-- Catch-all so an insert can never fail on a missing month partition
-- (e.g. if the ensure job lapses); prune_telemetry never DROPs this one.
CREATE TABLE v2_telemetry_samples_default PARTITION OF v2_telemetry_samples DEFAULT;

-- Cover a window around the migration date; the ensure command extends it.
DO $$
DECLARE d date;
BEGIN
    FOR d IN
        SELECT generate_series(
            date_trunc('month', now()) - interval '1 month',
            date_trunc('month', now()) + interval '3 months',
            interval '1 month'
        )::date
    LOOP
        PERFORM telemetry_ensure_partition(d);
    END LOOP;
END $$;
"""

_DROP_SAMPLES = r"""
DROP TABLE IF EXISTS v2_telemetry_samples CASCADE;
DROP FUNCTION IF EXISTS telemetry_ensure_partition(date);
"""


